; 主引导程序
; --------------------------------------------------
SECTION MBR vstart=0x7c00 ; 把起始地址编译为 0x7c00
    mov ax, cs     ; cs 代码段寄存器
    mov ds, ax     ; dx 数据段寄存器
    mov es, ax     ; es 附加段寄存器
    mov ss, ax     ; ss 堆栈段寄存器
    mov fs, ax     ; fs 80386 后添加的寄存器，无全称
    mov sp, 0x7c00 ; sp 堆栈指针寄存器

; 清屏
; --------------------------------------------------
; INT 0x10    功能号: 0x06    功能描述：上卷窗口
; --------------------------------------------------
; 输入：
; AH 功能号 = 0x06
; AL = 上卷的行数(如果为0，表示全部)
; BH = 上卷行属性
; (CL, CH) = 窗口左上角的 (X, Y) 位置
; (DL, DH) = 窗口右下角的 (X, Y) 位置
; 无返回值:
    mov ax, 0x600
    mov bx, 0x700
    mov cx, 0	   ; 左上角: (0, 0)
    mov dx, 0x184f ; 右下角: (80, 25)
                   ; VGA 文本模式种，一行只能容纳 80 个字符，共 25 行
                   ; 下标从 0 开始，所以 0x18=24, 0x4f=79
    int 0x10       ; int 0x10

;;;;;;;;;	下面这三行代码获取光标位置	;;;;;;;;;
; .get_cursor 获取当前光标位置，在光标处打印字符
    mov ah, 3      ; 3 号子功能
    mov bh, 0      ; 待获取光标的页号

    int 0x10       ; 输出：ch = 光标开始行，cl = 光标结束行
                   ; dh = 光标所在行号，dl = 光标所在列号

;;;;;;;;;	获取光标位置结束	;;;;;;;;;

;;;;;;;;;	打印字符串	;;;;;;;;;
	;还是用10h中断，不过这次调用13号子功能打印字符串
    mov ax, message
    mov bp, ax     ; es:bp 为串首地址，es此时同cs一致
    			   ; 开头时已经为sreg初始化

	; 光标位置要用到dx寄存器中内容，cx中的光标位置可忽略
    mov cx, 5      ; cx 为串长度，不包括结束符 '\0'的字符个数
    mov ax, 0x1301 ; 子功能号 13 显示字符及属性，要存入 ah 寄存器，
                   ; al 设置写字符方式 ah = 01: 显示字符串，光标跟随移动
    mov bx, 0x2    ; bh 存储要显示的页号，此处是第0页，
                   ; bl 中是字符属性，属性黑底绿字(bl = 02)
    int 0x10	   ; 执行BIOS 0x10 号中断
;;;;;;;;;	打字字符串结束	;;;;;;;;;

    jmp $          ; 程序悬停在此

    message db "1 MBR"    ; db 字节型 dw 字类型 dd 双字型 dq 四字型 dt 十字节型
    times 510-($-$$) db 0 ; 填充文件末尾的魔数 0xaa55 和当前位置之间的空间
                          ; 保证编译后生成的文件大小为 512 字节（硬盘一个扇区的大小）
    db 0x55, 0xaa
